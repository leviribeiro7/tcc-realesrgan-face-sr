    with torch.inference_mode():
        hr_image = gen(img)
    gen_out = deepcopy(hr_image)
    print(f'generator output shape: {gen_out.shape}')
    hr_image = hr_image.data.squeeze().float().cpu().clamp_(0, 1).numpy()
